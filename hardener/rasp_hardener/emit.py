"""Generate public build identity, encrypted literal tables, and private symbol mappings.

The literal registry supplies all protected bytes. Detector order stays in the private
manifest; build_generated.h carries only the public build ID. Only literals.c emits
storage for build_seed.h, preventing duplicate tables in other translation units.
"""

from __future__ import annotations

import pathlib

from rasp_hardener import strenc
from rasp_hardener import literals
from rasp_hardener import names
from rasp_hardener import seed

_AUTOGEN = "/* Generated by rasp-hardener. Do not edit; regenerate from the build seed. */"


def _c_bytes(data: bytes) -> str:
    """Format bytes as a comma-separated C initializer list of 0xNN values."""
    return ", ".join(f"0x{b:02x}" for b in data)


def render_build_generated_h(profile: seed.BuildProfile) -> str:
    return "\n".join(
        [
            _AUTOGEN,
            "#ifndef RASP_BUILD_GENERATED_H",
            "#define RASP_BUILD_GENERATED_H",
            "",
            f'#define RASP_BUILD_ID "{profile.build_id}"',
            "",
            "#endif",
            "",
        ]
    )


def render_build_seed_h(profile: seed.BuildProfile, raw_literals: list[literals.Literal]) -> str:
    """Render build_seed.h from the parsed literal registry (rasp_hardener.literals).

    The generated table is deliberately anonymous (``r_g<N>`` arrays behind ``RASP_STR_<NAME>`` macro
    aliases), so no registry name or plaintext reaches the binary's symbol tables. literals.c includes
    this header with RASP_LITERALS_IMPL defined, so the static tables live in exactly one TU.
    """
    table = strenc.encrypt_table({lit.name: lit.text for lit in raw_literals}, profile.string_key)

    lines = [
        _AUTOGEN,
        "#ifndef RASP_BUILD_SEED_H",
        "#define RASP_BUILD_SEED_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "/* Per-build VM opcode assignments (design Subsystem 3: the ISA is permuted per build). */",
    ]
    for name in seed.BASE_OPCODES:
        lines.append(f"#define RASP_OP_{name} 0x{profile.opcode_map[name]:02x}")
    lines += [
        "",
        "#ifdef RASP_LITERALS_IMPL",
        f"typedef char r_slot_count_check[(RASP_SLOT_COUNT == {len(table)}) ? 1 : -1];",
        "/* Per-build key stream for rasp_strobf_decode (see strobf.c / strenc.py). */",
        f"static const uint8_t r_lkey[{strenc.KEY_LEN}] = {{ {_c_bytes(profile.string_key)} }};",
        "",
        "/* Encrypted string table: literals kept out of .rodata, decrypted on use. */",
    ]
    for idx, entry in enumerate(table):
        lines += [
            f"typedef char r_slot_check{idx}[(RASP_SLOT_{entry.name} == {idx}) ? 1 : -1];",
            f"/* [{idx}] hidden */",
            f"static const uint8_t r_g{idx}[] = {{ {_c_bytes(entry.cipher)} }};",
        ]
    lines.append(f"static const uint8_t *const r_lits[{len(table)}] = {{")
    lines.append("    " + ", ".join(f"r_g{i}" for i in range(len(table))) + ",")
    lines.append("};")
    lines.append(f"static const unsigned short r_lit_lens[{len(table)}] = {{")
    lines.append("    " + ", ".join(str(len(e.cipher)) for e in table) + ",")
    lines.append("};")
    lines += ["#endif /* RASP_LITERALS_IMPL */", ""]
    for idx, entry in enumerate(table):
        ident = f"RASP_STR_{entry.name}"
        # The plaintext is deliberately not written into the header — that would defeat the encryption.
        # The r_g<N> alias only resolves where RASP_LITERALS_IMPL is set (literals.c), by design.
        lines += [
            f"#define {ident} r_g{idx}",
            f"#define {ident}_LEN {len(entry.cipher)}",
            f"#define {ident}_IDX {idx}",
        ]
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def render_integrity_regions_h(regions: list[tuple[int, int]]) -> str:
    """Render the code/read-only `.so` regions the device hashes at runtime (design §8) as a C header.

    Consumed by ``rasp_jni.c`` (guarded by ``__has_include``): when present the report is sealed with the
    integrity-derived key. `regions` is a list of ``(file_offset, length)`` from ``codehash.so_integrity_root``.
    """
    lines = [
        _AUTOGEN,
        "#ifndef RASP_INTEGRITY_REGIONS_H",
        "#define RASP_INTEGRITY_REGIONS_H",
        "",
        '#include "integrity.h"',
        "",
        "static const rasp_file_region_t RASP_INTEGRITY_REGIONS[] = {",
    ]
    lines += [f"    {{ {off}ULL, {size}ULL }}," for (off, size) in regions]
    lines += [
        "};",
        f"#define RASP_INTEGRITY_REGION_COUNT {len(regions)}",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def emit_headers(
    profile: seed.BuildProfile, out_dir: str | pathlib.Path, raw_literals: list[literals.Literal]
) -> list[pathlib.Path]:
    """Write ``build_generated.h`` and ``build_seed.h`` into `out_dir`. Returns the paths written."""
    out = pathlib.Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    generated = out / "build_generated.h"
    seed = out / "build_seed.h"
    generated.write_text(render_build_generated_h(profile))
    seed.write_text(render_build_seed_h(profile, raw_literals))
    return [generated, seed]


def render_build_names_h(profile: seed.BuildProfile, symbols: list[str]) -> str:
    """Per-build macro renames; without this header the names compile unchanged (dev builds)."""
    renames = names.rename_map(symbols, profile.string_key)
    lines = [_AUTOGEN, "#ifndef RASP_BUILD_NAMES_H", "#define RASP_BUILD_NAMES_H", ""]
    for sym, pseudo in renames.items():
        lines.append(f"#define {sym} {pseudo}")
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def render_symbols_map(profile: seed.BuildProfile, symbols: list[str]) -> dict[str, str]:
    """{pseudonym: real symbol} for crash mapping. Build artifact; gitignored."""
    return {p: sym for sym, p in names.rename_map(symbols, profile.string_key).items()}
