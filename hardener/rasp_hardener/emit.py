"""Header generation: turns a :class:`~rasp_hardener.seed.BuildProfile` into C headers the native build consumes.

Two headers are emitted:

- ``build_generated.h`` — the concrete ``RASP_BUILD_ID`` / ``RASP_BUILD_KEY_HEX`` for this build. ``build_config.h``
  includes it when present (via ``__has_include``) and otherwise falls back to the committed dev defaults, so the
  host tests keep building unhardened while a real build overrides them.
- ``build_seed.h`` — the per-build VM opcode assignments, the detector order, the string key stream, and the
  encrypted string table (see :mod:`strenc`). This is what makes each build's native layer polymorphic.

Everything here is generated text; nothing is compiled by the hardener. The cross-language test compiles the
output against ``strobf.c`` to prove the encrypted table decrypts back to the original strings on the C side.
"""

from __future__ import annotations

import pathlib

from rasp_hardener import strenc
from rasp_hardener.seed import BASE_OPCODES, BuildProfile

# The literals currently sitting in cleartext in rasp_jni.c. In a hardened build these move into the encrypted
# table and are decrypted into a stack buffer at registration time. Order fixes each entry's table index.
DEFAULT_STRINGS: dict[str, str] = {
    "TARGET_CLASS": "dev/ostorlab/rasp/flutter_rasp/NativeDetectors",
    "M_SCAN": "nativeScan",
    "M_SEAL": "nativeSeal",
    "SIG_SCAN": "()Ljava/lang/String;",
    "SIG_SEAL": "(Ljava/lang/String;Ljava/lang/String;J)Ljava/lang/String;",
}

_AUTOGEN = "/* Generated by rasp-hardener. Do not edit; regenerate from the build seed. */"


def _c_bytes(data: bytes) -> str:
    """Format bytes as a comma-separated C initializer list of 0xNN values."""
    return ", ".join(f"0x{b:02x}" for b in data)


def render_build_generated_h(profile: BuildProfile) -> str:
    return "\n".join(
        [
            _AUTOGEN,
            "#ifndef RASP_BUILD_GENERATED_H",
            "#define RASP_BUILD_GENERATED_H",
            "",
            f'#define RASP_BUILD_ID "{profile.build_id}"',
            f'#define RASP_BUILD_KEY_HEX "{profile.build_key_hex}"',
            "",
            "#endif",
            "",
        ]
    )


def render_build_seed_h(profile: BuildProfile, strings: dict[str, str] | None = None) -> str:
    strings = DEFAULT_STRINGS if strings is None else strings
    table = strenc.encrypt_table(strings, profile.string_key)

    lines = [
        _AUTOGEN,
        "#ifndef RASP_BUILD_SEED_H",
        "#define RASP_BUILD_SEED_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "/* Per-build VM opcode assignments (design Subsystem 3: the ISA is permuted per build). */",
    ]
    for name in BASE_OPCODES:
        lines.append(f"#define RASP_OP_{name} 0x{profile.opcode_map[name]:02x}")

    lines += [
        "",
        "/* Per-build detector order (canonical detector-id strings, permuted per build). */",
        f"#define RASP_DETECTOR_COUNT {len(profile.detector_order)}",
        "static const char *const RASP_DETECTOR_ORDER[] = {",
    ]
    lines += [f'    "{d}",' for d in profile.detector_order]
    lines += [
        "};",
        "",
        "/* Per-build key stream for rasp_strobf_decode (see strobf.c / strenc.py). */",
        f"static const uint8_t RASP_STRING_KEY[{strenc.KEY_LEN}] = {{ {_c_bytes(profile.string_key)} }};",
        "",
        "/* Encrypted string table: literals kept out of .rodata, decrypted on use. */",
    ]
    for idx, entry in enumerate(table):
        ident = f"RASP_STR_{entry.name}"
        # The plaintext is deliberately not written into the header — that would defeat the encryption.
        lines += [
            f"/* [{idx}] {ident} (plaintext hidden) */",
            f"static const uint8_t {ident}[] = {{ {_c_bytes(entry.cipher)} }};",
            f"#define {ident}_LEN {len(entry.cipher)}",
            f"#define {ident}_IDX {idx}",
        ]
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def render_integrity_regions_h(regions: list[tuple[int, int]]) -> str:
    """Render the code/read-only `.so` regions the device hashes at runtime (design §8) as a C header.

    Consumed by ``rasp_jni.c`` (guarded by ``__has_include``): when present the report is sealed with the
    integrity-derived key. `regions` is a list of ``(file_offset, length)`` from ``codehash.so_integrity_root``.
    """
    lines = [
        _AUTOGEN,
        "#ifndef RASP_INTEGRITY_REGIONS_H",
        "#define RASP_INTEGRITY_REGIONS_H",
        "",
        '#include "integrity.h"',
        "",
        "static const rasp_file_region_t RASP_INTEGRITY_REGIONS[] = {",
    ]
    lines += [f"    {{ {off}ULL, {size}ULL }}," for (off, size) in regions]
    lines += [
        "};",
        f"#define RASP_INTEGRITY_REGION_COUNT {len(regions)}",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def emit_headers(
    profile: BuildProfile, out_dir: str | pathlib.Path, strings: dict[str, str] | None = None
) -> list[pathlib.Path]:
    """Write ``build_generated.h`` and ``build_seed.h`` into `out_dir`. Returns the paths written."""
    out = pathlib.Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    generated = out / "build_generated.h"
    seed = out / "build_seed.h"
    generated.write_text(render_build_generated_h(profile))
    seed.write_text(render_build_seed_h(profile, strings))
    return [generated, seed]
