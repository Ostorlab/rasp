"""Generates the key-derivation builder ("code-as-data" shovel) for one target.

Compiles src/selfdecrypt/kdf_blob.c for the target, extracts the machine code of its whole .text (verified
self-contained: no relocations, no external symbols, no .rodata), and writes two files into the output directory:

    kdf_shovel.h   -- kKdfBlobLen, kKdfBlobEntry, and the kdf_shovel_emit declaration
    kdf_shovel.cpp -- kdf_shovel_emit(page): writes the blob bytes into `page` as a run of volatile immediate stores,
                      the way Raqami's packer materialises code, so the derivation is not present as .text. The bootstrap
                      (selfdecrypt.cpp) maps an RWX page, calls this, and branches into it.

Run from runtime/android/CMakeLists.txt, per ABI:

    gen_kdf_shovel.py --cc <clang> --target <triple> --arch <aarch64|x86_64> --src <kdf_blob.c> --out-dir <dir>
"""

from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys

_BASE_FLAGS = [
    "-O2",
    "-ffreestanding",
    "-fno-builtin",
    "-fno-stack-protector",
    "-fno-jump-tables",
    "-fomit-frame-pointer",
    "-fno-vectorize",
    "-fno-slp-vectorize",
    "-fPIC",
]


def _tool(cc: str, name: str) -> str:
    """Resolves an llvm binutil (objcopy/nm/readelf) next to the given clang."""
    candidate = pathlib.Path(cc).resolve().parent / f"llvm-{name}"
    return str(candidate) if candidate.exists() else name


def _blob(cc: str, target: str, arch: str, src: str, work: pathlib.Path) -> tuple[bytes, dict[str, int]]:
    """Compiles the blob, verifies it is self-contained, and returns (text_bytes, entry_offsets)."""
    obj = work / "kdf_blob.o"
    binf = work / "kdf_blob.bin"
    flags = list(_BASE_FLAGS)
    if arch == "x86_64":
        flags.append("-mno-sse")

    subprocess.run([cc, f"--target={target}", *flags, "-c", src, "-o", str(obj)], check=True)

    readelf = _tool(cc, "readelf")
    nm = _tool(cc, "nm")
    objcopy = _tool(cc, "objcopy")

    relocs = subprocess.run([readelf, "-rW", str(obj)], check=True, capture_output=True, text=True).stdout
    reloc_lines = [line for line in relocs.splitlines() if " R_" in line]
    if reloc_lines:
        raise SystemExit(f"kdf_blob is not relocation-free for {target}:\n" + "\n".join(reloc_lines[:8]))
    undefined = subprocess.run([nm, "-u", str(obj)], check=True, capture_output=True, text=True).stdout.strip()
    if undefined:
        raise SystemExit(f"kdf_blob references external symbols for {target}:\n{undefined}")

    subprocess.run([objcopy, "--dump-section", f".text={binf}", str(obj)], check=True)
    text = binf.read_bytes()

    entries: dict[str, int] = {}
    for line in subprocess.run([nm, str(obj)], check=True, capture_output=True, text=True).stdout.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[2] in ("kdf_blob", "verify_blob"):
            entries[parts[2]] = int(parts[0], 16)
    missing = {"kdf_blob", "verify_blob"} - set(entries)
    if missing:
        raise SystemExit(f"symbols not found: {sorted(missing)}")
    return text, entries


def _emit(out_dir: pathlib.Path, text: bytes, entries: dict[str, int]) -> None:
    """Writes kdf_shovel.h and kdf_shovel.cpp for the given blob bytes."""
    padded = text + b"\x00" * ((-len(text)) % 8)
    words = [int.from_bytes(padded[i : i + 8], "little") for i in range(0, len(padded), 8)]

    (out_dir / "kdf_shovel.h").write_text(
        "/// Generated by gen_kdf_shovel.py -- do not edit.\n\n"
        "#pragma once\n\n"
        "#include <cstddef>\n\n"
        "namespace rasp::android::selfdecrypt {\n\n"
        "/// The length of the key-derivation blob, in bytes (a multiple of eight).\n"
        f"inline constexpr std::size_t kKdfBlobLen = {len(padded)};\n\n"
        "/// The offset of the key-derivation entry point within the materialised bytes.\n"
        f"inline constexpr std::size_t kKdfBlobEntry = {entries['kdf_blob']};\n\n"
        "/// The offset of the post-decrypt verification entry point within the materialised bytes.\n"
        f"inline constexpr std::size_t kVerifyBlobEntry = {entries['verify_blob']};\n\n"
        "/// Writes the key-derivation blob into `page` as a run of immediate stores.\n"
        "void kdf_shovel_emit(unsigned char* page);\n\n"
        "}  // namespace rasp::android::selfdecrypt\n"
    )

    lines = [
        "/// Generated by gen_kdf_shovel.py -- do not edit. The key-derivation machine code, materialised as immediate",
        "/// stores so it is not present as disassemblable .text. Lives in the clear .stubcode.",
        "",
        '#include "kdf_shovel.h"',
        "",
        "#include <cstdint>",
        "",
        '#pragma clang section text = ".stubcode" rodata = ".stubrodata"',
        "",
        "namespace rasp::android::selfdecrypt {",
        "",
        "void kdf_shovel_emit(unsigned char* page) {",
        "  volatile std::uint64_t* p = reinterpret_cast<volatile std::uint64_t*>(page);",
    ]
    lines.extend(f"  p[{index}] = 0x{word:016x}ULL;" for index, word in enumerate(words))
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace rasp::android::selfdecrypt")
    (out_dir / "kdf_shovel.cpp").write_text("\n".join(lines) + "\n")


def main(argv: list[str]) -> int:
    """Generates the shovel for one target. Returns an exit code."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cc", required=True)
    parser.add_argument("--target", required=True)
    parser.add_argument("--arch", required=True, choices=["aarch64", "x86_64"])
    parser.add_argument("--src", required=True)
    parser.add_argument("--out-dir", required=True)
    args = parser.parse_args(argv)

    out_dir = pathlib.Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    work = out_dir / "_kdf_work"
    work.mkdir(exist_ok=True)

    text, entries = _blob(args.cc, args.target, args.arch, args.src, work)
    _emit(out_dir, text, entries)
    print(
        f"gen_kdf_shovel: {args.arch} blob={len(text)} bytes kdf={entries['kdf_blob']} verify={entries['verify_blob']}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
