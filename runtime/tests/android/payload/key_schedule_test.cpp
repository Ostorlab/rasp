TEST(Package, digest_whenTheApkSitsInItsInstallDirectory_hashesTheDirectoryBeforeTheFirstDash) {
  // The random suffix is base64, so it can hold dashes of its own: only the first one separates
  // the package, which cannot contain one.
  const std::optional<Key> digest =
      package_digest("/data/app/~~wrGIztjHmk9ddFdqhji5aA==/app.alkahf-TVq-2KMp-660/base.apk");
  ASSERT_TRUE(digest.has_value());
  const std::string package = "app.alkahf";
  const std::span package_bytes{
      // NOLINTNEXTLINE(cppcoreguidelines-pro-type-reinterpret-cast)
      reinterpret_cast<const std::uint8_t*>(package.data()),
      package.size(),
  };
  const std::optional<Key> expected = checks::sha256(package_bytes);
  ASSERT_TRUE(expected.has_value());
  EXPECT_EQ(*digest, *expected);
}

TEST(Package, digest_whenTheApkIsTheOnlyFileInItsDirectory_hashesTheWholeDirectoryName) {
  // The plain layout of an older install names the directory `<package>-<number>`, and the modern
  // one wraps it in a random parent: the first dash still separates the package.
  const std::optional<Key> digest = package_digest("/data/app/app.alkahf-1/base.apk");
  const std::optional<Key> tokened = package_digest("/data/app/~~x==/app.alkahf-1==/base.apk");
  ASSERT_TRUE(digest.has_value());
  ASSERT_TRUE(tokened.has_value());
  EXPECT_EQ(*digest, *tokened);
}

TEST(Package, digest_whenThePathHoldsNoPackageName_returnsNothing) {
  EXPECT_FALSE(package_digest("base.apk").has_value());
  EXPECT_FALSE(package_digest("/base.apk").has_value());
  EXPECT_FALSE(package_digest("").has_value());
}

TEST(Fold, chains_whenReordered_changeTheirStates) {
  const std::array<Key, 3> inputs{
      from_key("000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f"),
      from_key("202122232425262728292a2b2c2d2e2f303132333435363738393a3b3c3d3e3f"),
      from_key("404142434445464748494a4b4c4d4e4f505152535455565758595a5b5c5d5e5f"),
  };
  const Key first = fold_chain(Key{}, std::span<const Key>(inputs), "a");
  const std::array<Key, 3> reordered{
      inputs[2],
      inputs[1],
      inputs[0],
  };

  const Key second = fold_chain(Key{}, std::span<const Key>(reordered), "a");

  EXPECT_NE(first, second);
}

