/// scattered_seed: reconstructs the at-rest seed at runtime from many small constants, so it is never a contiguous
/// plaintext blob in the binary.
///
/// The naive place for the at-rest seed is a named section such as `__rasp_config`, which an attacker dumps in one
/// scan. Instead the seed's bytes are produced by a function that mixes many small per-build constants, each of which
/// the obfuscator's opaque-constants pass rewrites independently. There is no single resident copy of the seed to
/// find; an attacker must trace the reconstruction through obfuscated code to recover it, which is the cost this
/// raises. It is not secrecy (the attacker can still recover it by reversing the code) but it removes the free dump.
///
/// The per-build constants are generated by the build (a header the packer or a build step writes) so each release
/// scatters a different seed; this header declares the interface the generated constants feed.

#pragma once

#include <array>
#include <cstddef>
#include <cstdint>

namespace rasp::ios::selfdecrypt {

/// The size of the reconstructed seed, in bytes.
inline constexpr std::size_t kSeedBytes = 32;

/// Reconstructs the at-rest seed into `out`.
///
/// The bytes are computed, not copied from one place: the implementation folds the scattered per-build constants
/// together so no step holds the whole seed in a single named object. The caller uses the seed immediately and does not
/// keep it.
///
/// @param out Filled with the kSeedBytes reconstructed seed bytes.
void reconstruct_seed(std::array<std::uint8_t, kSeedBytes>& out);

}  // namespace rasp::ios::selfdecrypt
